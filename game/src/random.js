// Seeded random numbers (mulberry32), so a staged screenshot or a replay
// of the same seed always unfolds the same way. The simulation itself is
// deterministic; the RNG is only for cosmetic sparkle and smoke drift.
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
